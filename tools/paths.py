"""Раскладка каталогов проекта — единственное место, где она задана.

Пути отсчитываются от корня репозитория, а не от текущей папки, поэтому
инструменты можно запускать откуда угодно.

* `dataset/` — закоммиченные опорные кадры, раскладки HUD, проекция экрана
  на карту и каталог каналов;
* `data/` — локальные исходники и производные наборы для обучения (в Git не
  идут): ролики и плотный набор «кадр → координаты камеры»;
* `runs/` — всё, что получилось при запусках инструментов (в Git не идёт).
  Прогон модели — это папка `runs/<направление>/<прогон>/` со всем своим:
  чекпоинтом, отчётом, логом обучения и результатами проверок.
"""

